"""Regenerate thin public action entry points from the canonical action metadata."""

from __future__ import annotations

import argparse
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parents[1]
PRIMARY = "test-impact"


def entry_points():
    for source in sorted((ROOT / ".github/actions").glob("*/action.yml")):
        original = yaml.safe_load(source.read_text())
        public = {key: original[key] for key in ("name", "description")}
        if original.get("inputs"):
            public["inputs"] = original["inputs"]
        if original.get("outputs"):
            public["outputs"] = {
                key: {"description": value["description"], "value": "${{ steps.action.outputs." + key + " }}"}
                for key, value in original["outputs"].items()
            }
        step = {"id": "action", "uses": "$/" + source.parent.relative_to(ROOT).as_posix()}
        if original.get("inputs"):
            step["with"] = {key: "${{ inputs." + key + " }}" for key in original["inputs"]}
        public["runs"] = {"using": "composite", "steps": [step]}
        content = "# Generated by scripts/public_actions.py; edit the canonical .github/actions metadata.\n"
        content += yaml.safe_dump(public, sort_keys=False, width=120)
        yield ROOT / source.parent.name / "action.yml", content
        if source.parent.name == PRIMARY:
            yield ROOT / "action.yml", content


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    stale = []
    for path, content in entry_points():
        if args.check:
            if not path.exists() or path.read_text() != content:
                stale.append(str(path.relative_to(ROOT)))
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(content)
    if stale:
        print("Refresh public action contracts: uv run python scripts/public_actions.py")
        print("\n".join(stale))
    return bool(stale)


if __name__ == "__main__":
    raise SystemExit(main())
